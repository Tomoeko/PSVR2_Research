/*
 * Exact 06.00 sieusb.ko static command-report storage.  IDA's linked-image
 * address for unk_8570 is 0x8570: .bss+0x70.  The live module loader places
 * .bss at text+0x9180 after discarding the init sections, so the slot array is
 * at text+0x91f0.  usb_cmd_init proves that the region contains all 256
 * 0x210-byte slots.  The exact IN request selects a slot with wValue's low
 * byte, which lets the host verify the staged image immediately before use.
 * Slot 0x10 avoids the active low-numbered command channels observed during
 * normal authentication traffic.
 */
#define PSVR2_SIEUSB_BASE UINT64_C(0xffffffbffc0a6000)
#define PSVR2_SIEUSB_BSS_OFFSET UINT64_C(0x9180)
#define PSVR2_SIEUSB_COMMAND_SLOTS_BSS_OFFSET UINT64_C(0x70)
#define PSVR2_SIEUSB_COMMAND_SLOTS \
    (PSVR2_SIEUSB_BASE + PSVR2_SIEUSB_BSS_OFFSET + \
     PSVR2_SIEUSB_COMMAND_SLOTS_BSS_OFFSET)
#define PSVR2_COLD_STATIC_SLOT UINT64_C(0x10)
#define PSVR2_COLD_STATIC_SLOT_STRIDE UINT64_C(0x210)
#define PSVR2_COLD_STATIC_STAGE \
    (PSVR2_SIEUSB_COMMAND_SLOTS + \
     PSVR2_COLD_STATIC_SLOT * PSVR2_COLD_STATIC_SLOT_STRIDE)

